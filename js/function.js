function addToCart(productId) {
  const product = products.find((entry) => entry.id === productId);
  if (!product) {
    console.error(`Unknown product: ${productId}`);
    return;
  }

  const input = document.querySelector(
    `[data-quantity-for="${CSS.escape(productId)}"]`,
  );
  const quantity = input ? Number.parseInt(input.value, 10) : 1;
  if (!Number.isInteger(quantity) || quantity < 1 || quantity > 99) {
    setProductQuantity(productId, 1);
    return;
  }

  const sizeSelect = document.querySelector(
    `[data-size-for="${CSS.escape(productId)}"]`,
  );
  const variant = sizeSelect ? sizeSelect.value : "";
  if (sizeSelect && !variant) {
    sizeSelect.focus();
    sizeSelect.setCustomValidity(
      currentLanguage === "ta"
        ? "முதலில் அளவைத் தேர்ந்தெடுக்கவும்."
        : "Please choose a size first.",
    );
    sizeSelect.reportValidity();
    sizeSelect.addEventListener(
      "change",
      () => sizeSelect.setCustomValidity(""),
      { once: true },
    );
    return;
  }

  selectedVariants.set(productId, variant);
  const key = `${productId}:${variant}`;
  const existingItem = cart.find((item) => item.key === key);
  if (existingItem) {
    existingItem.quantity = Math.min(99, existingItem.quantity + quantity);
  } else {
    cart.push({ key, product, quantity, variant });
  }

  saveSharedCart();
  renderCart();
  document.querySelector("#toastProductName").textContent =
    product.name[currentLanguage];
  window.bootstrap.Toast.getOrCreateInstance(
    document.querySelector("#orderToast"),
  ).show();
}

function changeCartQuantity(key, change) {
  const item = cart.find((entry) => entry.key === key);
  if (!item) {
    console.error(`Unknown cart item: ${key}`);
    return;
  }

  item.quantity += change;
  item.quantity = Math.min(99, item.quantity);
  if (item.quantity < 1) {
    cart = cart.filter((entry) => entry.key !== key);
  }
  saveSharedCart();
  renderCart();
}

