function openWhatsAppOrder(customer) {
  if (!cart.length) {
    console.error("Cannot start a WhatsApp order with an empty cart.");
    return;
  }
  const url = `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(orderMessage(customer))}`;
  window.open(url, "_blank", "noopener,noreferrer");
}

function updateCustomerFormState(showError = false) {
  const form = document.querySelector("#customerDetailsForm");
  const submitButton = document.querySelector("#drawerWhatsappOrder");
  const errorMessage = document.querySelector("#customerFormError");

  form.querySelectorAll("input[required]").forEach((input) => {
    input.setCustomValidity(input.value.trim() ? "" : t("customerFormError"));
  });

  const isValid = form.checkValidity() && cart.length > 0;
  submitButton.disabled = !isValid;
  errorMessage.hidden = !showError || isValid;
  return isValid;
}

function handleOrderSubmission(event) {
  event.preventDefault();
  if (!updateCustomerFormState(true)) {
    const form = document.querySelector("#customerDetailsForm");
    const invalidField = form.querySelector(":invalid");
    invalidField?.focus();
    form.reportValidity();
    return;
  }

  const formData = new FormData(event.currentTarget);
  const customer = {
    name: formData.get("customerName").trim(),
    mobile: formData.get("customerMobile").trim(),
    email: formData.get("email").trim(),
    doorNo: formData.get("doorNo").trim(),
    street: formData.get("street").trim(),
    place: formData.get("place").trim(),
    landmark: formData.get("landmark").trim(),
  };
  openWhatsAppOrder(customer);
}

