function loadSharedCart() {
  const storedCart = localStorage.getItem(cartStorageKey);
  if (!storedCart) {
    return [];
  }
  try {
    const savedCart = JSON.parse(storedCart);
    if (!Array.isArray(savedCart)) {
      throw new TypeError("Saved order must be an array.");
    }
    return savedCart.filter(
      (item) =>
        item &&
        typeof item.key === "string" &&
        item.product &&
        typeof item.product.id === "string" &&
        item.product.name &&
        Number.isInteger(item.quantity) &&
        item.quantity > 0,
    );
  } catch (error) {
    console.error("Unable to load the saved order.", error);
    return [];
  }
}

