document.addEventListener("input", (event) => {
  const input = event.target.closest("[data-quantity-for]");
  if (input) {
    setProductQuantity(input.dataset.quantityFor, input.value);
  }
});

document.addEventListener("change", (event) => {
  if (event.target.matches("[data-quantity-for]")) {
    setProductQuantity(event.target.dataset.quantityFor, event.target.value);
  } else if (event.target.matches("[data-size-for]")) {
    setProductVariant(event.target.dataset.sizeFor, event.target.value);
  }
});

document.addEventListener("click", (event) => {
  const stepButton = event.target.closest("[data-quantity-step]");
  if (stepButton) {
    const productId = stepButton.dataset.productId;
    const quantity = quantities.get(productId) || 1;
    setProductQuantity(
      productId,
      quantity + Number(stepButton.dataset.quantityStep),
    );
    return;
  }

  const addButton = event.target.closest("[data-add-product]");
  if (addButton) {
    addToCart(addButton.dataset.addProduct);
    return;
  }

  const cartStep = event.target.closest("[data-cart-step]");
  if (cartStep) {
    changeCartQuantity(
      cartStep.dataset.cartKey,
      Number(cartStep.dataset.cartStep),
    );
    return;
  }

  const removeButton = event.target.closest("[data-remove-cart-key]");
  if (removeButton) {
    cart = cart.filter(
      (item) => item.key !== removeButton.dataset.removeCartKey,
    );
    saveSharedCart();
    renderCart();
  }
});

