async function loadCatalogs() {
  const catalogFiles = [
    { category: "groceries", file: "groceries.json" },
    { category: "clothing", file: "textiles.json" },
    { category: "jewellery", file: "jewels.json" },
  ];
  document.querySelectorAll(".product-grid").forEach((container) => {
    window.renderCatalogSkeleton(container);
  });

  const catalogResults = await Promise.allSettled(
    catalogFiles.map(async ({ file }) => {
      const response = await fetch(`./data/${file}`);
      if (!response.ok) {
        throw new Error(`Unable to load ${file}: ${response.status}`);
      }
      const catalog = await response.json();
      if (!Array.isArray(catalog)) {
        throw new TypeError(`Invalid product catalog: ${file}`);
      }
      return catalog;
    }),
  );
  products = [];
  catalogResults.forEach((result, index) => {
    const { category, file } = catalogFiles[index];
    const container = document.querySelector(`#${category}Products`);
    if (result.status === "fulfilled") {
      products.push(...result.value);
    } else {
      failedCatalogs.add(category);
      console.error(`Unable to load ${file}.`, result.reason);
    }
    if (container) {
      container.setAttribute("aria-busy", "false");
    }
  });
  catalogsLoaded = true;
  renderCatalogs();
  renderCart();
}

function parseOfferDate(value) {
  if (typeof value !== "string") {
    throw new TypeError("Offer date must be a DD-MM-YYYY string.");
  }
  const match = /^(\d{2})-(\d{2})-(\d{4})$/.exec(value);
  if (!match) {
    throw new TypeError(`Invalid offer date: ${value}`);
  }
  const [, dayText, monthText, yearText] = match;
  const date = new Date(
    Number(yearText),
    Number(monthText) - 1,
    Number(dayText),
  );
  if (
    date.getFullYear() !== Number(yearText) ||
    date.getMonth() !== Number(monthText) - 1 ||
    date.getDate() !== Number(dayText)
  ) {
    throw new TypeError(`Invalid offer date: ${value}`);
  }
  return date;
}

function renderOffer() {
  const section = document.querySelector("#specialOffer");
  if (!section) {
    return;
  }

  const offerText = document.querySelector("#offerText");
  const offerDate = document.querySelector("#offerDate");
  const offerBadge = document.querySelector("#offerBadge");
  section.setAttribute("aria-busy", String(offerState === "loading"));
  offerDate.hidden = true;
  offerBadge.hidden = true;

  if (offerState === "loading") {
    offerText.textContent = t("offerLoading");
    return;
  }
  if (offerState === "unavailable") {
    offerText.textContent = t("offerUnavailable");
    return;
  }
  if (!currentOffer) {
    offerText.textContent = t("noOfferToday");
    return;
  }

  offerText.textContent = t("offerText").replace(
    /\{percent\}/g,
    String(currentOffer.discount),
  );
  offerDate.textContent = `${t("offerDateLabel")} ${new Intl.DateTimeFormat(
    currentLanguage === "ta" ? "ta-IN" : "en-IN",
    { dateStyle: "long" },
  ).format(currentOffer.date)}`;
  offerDate.hidden = false;
  document.querySelector("#offerPercent").textContent =
    `${currentOffer.discount}%`;
  offerBadge.hidden = false;
}

async function loadOffer() {
  try {
    const response = await fetch("./data/offer.json");
    if (!response.ok) {
      throw new Error(`Unable to load offer.json: ${response.status}`);
    }
    const data = await response.json();
    if (!data || !Array.isArray(data.today_Offer)) {
      throw new TypeError("Invalid offer data: expected a today_Offer array.");
    }

    const offers = data.today_Offer.map((offer) => {
      if (
        !offer ||
        !Number.isInteger(offer.discount) ||
        offer.discount < 1 ||
        offer.discount > 100
      ) {
        throw new TypeError(
          "Invalid offer: discount must be an integer from 1 to 100.",
        );
      }
      return { date: parseOfferDate(offer.Date), discount: offer.discount };
    });
    const today = new Date();
    currentOffer =
      offers.find(
        (offer) =>
          offer.date.getFullYear() === today.getFullYear() &&
          offer.date.getMonth() === today.getMonth() &&
          offer.date.getDate() === today.getDate(),
      ) || null;
    offerState = "loaded";
  } catch (error) {
    console.error("Unable to load today's special offer.", error);
    currentOffer = null;
    offerState = "unavailable";
  }
  renderOffer();
}

function setProductQuantity(productId, requestedQuantity) {
  const quantity = Math.min(
    99,
    Math.max(1, Number.parseInt(requestedQuantity, 10) || 1),
  );
  quantities.set(productId, quantity);
  const input = document.querySelector(
    `[data-quantity-for="${CSS.escape(productId)}"]`,
  );
  if (input) {
    input.value = String(quantity);
  }
  const product = products.find((entry) => entry.id === productId);
  const lineTotal = document.querySelector(
    `[data-line-total-for="${CSS.escape(productId)}"]`,
  );
  if (product && lineTotal) {
    const unitPrice = getProductUnitPrice(
      product,
      selectedVariants.get(productId) || "",
    );
    lineTotal.textContent =
      unitPrice === undefined
        ? selectedVariants.get(productId)
          ? t("priceToConfirm")
          : t("sizePricePending")
        : formatPrice(unitPrice * quantity);
  }
}

function getProductUnitPrice(product, variant) {
  if (
    variant &&
    product.sizePrices &&
    Object.hasOwn(product.sizePrices, variant)
  ) {
    return product.sizePrices[variant];
  }
  return product.priceVariesBySize ? undefined : product.price;
}

